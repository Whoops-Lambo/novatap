import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,timeout:20000,args:['--no-sandbox','--disable-dev-shm-usage','--no-zygote','--disable-gpu']});
console.log("Browser launched");
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2});
await page.addInitScript(()=>{const fixture=sessionStorage.getItem('fixture');if(fixture){localStorage.setItem('novatap',fixture);sessionStorage.removeItem('fixture');}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
console.log('Navigating');
await page.goto('http://127.0.0.1:5173');
await page.locator('#orb').click();
await expect(page.locator('#dust')).toHaveText('1');
await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('novatap'))?.dust)).toBe(1);
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('novatap'));s.dust=500;s.total=500;sessionStorage.setItem('fixture',JSON.stringify(s));});
await page.reload();
await page.locator('#cards [data-buy="0"]').click();
await expect(page.locator('#rate')).toHaveText('0.5');
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('novatap'));s.last=Date.now()-3600000;sessionStorage.setItem('fixture',JSON.stringify(s));});
await page.reload();
await page.locator('#welcome').waitFor({state:'visible'});
assert.match(await page.locator('#offline-amount').textContent(),/1,800/);
await page.locator('#dismiss').click();
await page.locator('nav [data-tab="journey"]').click();
await page.locator('[data-claim="0"]').click();
await expect(page.locator('[data-claim="0"]')).toHaveText('Claimed');
// Timed expeditions persist, prevent multiple launches, and pay out once.
await page.locator('[data-launch="0"]').click();
await expect(page.locator('[data-launch="0"]')).toHaveText('In flight');
assert.equal(await page.locator('[data-launch="1"]').isDisabled(),true);
await page.reload();
await page.locator('nav [data-tab="journey"]').click();
assert.match(await page.locator('#route-status-0').textContent(),/Returns in/);
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('novatap'));s.expedition.ends=Date.now()-1000;sessionStorage.setItem('fixture',JSON.stringify(s));});
await page.reload();
await page.locator('nav [data-tab="journey"]').click();
await expect(page.locator('[data-launch="0"]')).toHaveText('Claim reward');
const before=await page.evaluate(()=>JSON.parse(localStorage.getItem('novatap')).dust);
await page.locator('[data-launch="0"]').click();
const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('novatap')).dust);
assert.ok(after>=before+150&&after<before+152);
assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('novatap')).expedition),null);
await page.screenshot({path:'/workspace/novatap/journey-screenshot.png',fullPage:true});
await page.locator('nav [data-tab="collect"]').click();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
// Buy a larger energy reserve, retain it after relaunch, and regenerate to the new cap.
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('novatap'));Object.assign(s,{dust:200,energy:0,energyLevel:0,levels:[0,0,0],last:Date.now()});sessionStorage.setItem('fixture',JSON.stringify(s));});
await page.reload();
await page.locator('.energy-link').click();
await page.locator('#buy-energy').click();
await expect(page.locator('#energy-description')).toHaveText(/600 to 700/);
await expect(page.locator('#buy-energy')).toBeDisabled();
assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('novatap')).dust),0);
await page.reload();
assert.match(await page.locator('#energy').textContent(),/100 \/ 600/);
assert.match(await page.locator('#regen').textContent(),/every 48s/);
await page.locator('#orb').click();
await expect(page.locator('#energy')).toHaveText(/99 \/ 600/);
await expect.poll(()=>page.evaluate(()=>Math.floor(JSON.parse(localStorage.getItem('novatap')).energy))).toBe(99);
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('novatap'));s.energy=0;s.last=Date.now()-4*3600000;sessionStorage.setItem('fixture',JSON.stringify(s));});
await page.reload();
assert.match(await page.locator('#energy').textContent(),/300 \/ 600/);
await page.setViewportSize({width:320,height:568});
await page.locator('.energy-link').click();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'/workspace/novatap/energy-upgrade-screenshot.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.locator('nav [data-tab="collect"]').click();
await page.screenshot({path:'/workspace/novatap/mobile-screenshot.png',fullPage:true});
await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'/workspace/novatap/desktop-screenshot.png',fullPage:true});
assert.deepEqual(errors,[]);console.log('PASS: mobile tapping, purchase, offline resume, milestone claim, expedition launch/persistence/reward, energy upgrade/persistence/offline recharge, responsive layout; no browser errors');
await browser.close();
